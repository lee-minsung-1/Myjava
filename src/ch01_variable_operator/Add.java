package ch01_variable_operator;

public class Add {
    static void main() {

        int x;
        int y;
        int result; // int타입으로 먼저 넣어줘야함

         x=4; //그래야지 x에다가 정수값을 저장할 수 있음
        y=5;
         result=x*y;

        System.out.println("x*y="+result);
        //ctrl+r= 원하는 단어를 원하는 다른 단어로 변환할 수 있는 단축어
    }
}
